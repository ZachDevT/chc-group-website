// Helper function to find matches in knowledge base
export const findBestMatch = (query, context = []) => {
  const lowerQuery = query.toLowerCase().trim()
  const words = lowerQuery.split(/\s+/)
  
  // Check for greetings
  const greetings = ['bonjour', 'salut', 'hello', 'bonsoir', 'bonne journée', 'bonne soirée', 'hi', 'hey']
  if (greetings.some(g => lowerQuery.includes(g))) {
    return {
      type: 'greeting',
      response: 'Bonjour! Je suis l\'assistant CHC Group. Comment puis-je vous aider aujourd\'hui?'
    }
  }

  // Check for farewells
  const farewells = ['au revoir', 'bye', 'à bientôt', 'merci', 'merci beaucoup', 'thanks']
  if (farewells.some(f => lowerQuery.includes(f))) {
    return {
      type: 'farewell',
      response: 'De rien! N\'hésitez pas à revenir si vous avez d\'autres questions. Bonne journée!'
    }
  }

  // Check for contact questions
  const contactKeywords = ['contact', 'joindre', 'appeler', 'téléphone', 'email', 'courriel', 'adresse', 'localisation', 'situé', 'où']
  if (contactKeywords.some(k => lowerQuery.includes(k))) {
    return {
      type: 'contact',
      response: `Vous pouvez nous contacter de plusieurs façons:
- Via le formulaire de contact sur notre site web
- Par email
- En utilisant le bouton WhatsApp disponible sur le site
- Notre équipe vous répondra dans les plus brefs délais.

CHC Group est basé en République Démocratique du Congo.`
    }
  }

  // Check for services
  for (const service of knowledgeBase.services) {
    const matchScore = service.keywords.filter(k => 
      lowerQuery.includes(k) || words.some(w => w.includes(k) || k.includes(w))
    ).length
    
    if (matchScore > 0) {
      return {
        type: 'service',
        service: service,
        response: `${service.title}\n\n${service.details}\n\n${service.description}`
      }
    }
  }

  // Check for sectors
  for (const sector of knowledgeBase.sectors) {
    const matchScore = sector.keywords.filter(k => 
      lowerQuery.includes(k) || words.some(w => w.includes(k) || k.includes(w))
    ).length
    
    if (matchScore > 0) {
      return {
        type: 'sector',
        sector: sector,
        response: `${sector.title}\n\n${sector.details}\n\n${sector.description}`
      }
    }
  }

  // Check for team members
  for (const member of knowledgeBase.team) {
    if (member.keywords.some(k => lowerQuery.includes(k))) {
      return {
        type: 'team',
        member: member,
        response: `${member.name}\n${member.role} - ${member.title}\n\n${member.description}`
      }
    }
  }

  // Check for company info
  const companyKeywords = ['qui', 'quoi', 'entreprise', 'cabinet', 'chc', 'groupe', 'société', 'organisation']
  if (companyKeywords.some(k => lowerQuery.includes(k)) || lowerQuery.includes('qui êtes')) {
    return {
      type: 'company',
      response: `${knowledgeBase.company.fullName}\n\n${knowledgeBase.company.description}\n\n${knowledgeBase.company.tagline}\n\nNous sommes basés en ${knowledgeBase.company.location}.`
    }
  }

  // Check for vision/mission
  if (lowerQuery.includes('vision')) {
    return {
      type: 'vision',
      response: `Notre Vision:\n\n${knowledgeBase.vision}`
    }
  }

  if (lowerQuery.includes('mission')) {
    return {
      type: 'mission',
      response: `Notre Mission:\n\n${knowledgeBase.mission}`
    }
  }

  // Check for expertise
  const expertiseKeywords = ['expertise', 'compétence', 'spécialité', 'domaine', 'savoir-faire']
  if (expertiseKeywords.some(k => lowerQuery.includes(k))) {
    return {
      type: 'expertise',
      response: `Nos domaines d'expertise incluent:\n\n${knowledgeBase.expertise.join('\n- ')}\n\nNous disposons d'une large gamme d'expertises pour apporter une réponse adaptée à vos défis de gestion et développement.`
    }
  }

  // Check for "what" or "list" questions
  if (lowerQuery.includes('quoi') || lowerQuery.includes('liste') || lowerQuery.includes('quels')) {
    if (lowerQuery.includes('service')) {
      const servicesList = knowledgeBase.services.map(s => `- ${s.title}: ${s.description}`).join('\n\n')
      return {
        type: 'services_list',
        response: `Nos services incluent:\n\n${servicesList}\n\nSouhaitez-vous plus d'informations sur un service spécifique?`
      }
    }
    
    if (lowerQuery.includes('secteur')) {
      const sectorsList = knowledgeBase.sectors.map(s => `- ${s.title}: ${s.description}`).join('\n\n')
      return {
        type: 'sectors_list',
        response: `Nos secteurs d'activités incluent:\n\n${sectorsList}\n\nSouhaitez-vous plus d'informations sur un secteur spécifique?`
      }
    }
  }

  // Use context from previous messages
  if (context.length > 0) {
    const lastBotMessage = context[context.length - 1]?.text?.toLowerCase() || ''
    
    // If last message was about a service, provide more details
    if (lastBotMessage.includes('service')) {
      if (lowerQuery.includes('détail') || lowerQuery.includes('plus') || lowerQuery.includes('explique')) {
        return {
          type: 'context_followup',
          response: 'Pour plus de détails sur nos services, je vous invite à visiter la page Services sur notre site web ou à nous contacter directement via le formulaire de contact ou WhatsApp.'
        }
      }
    }
  }

  // Default response with helpful suggestions
  return {
    type: 'default',
    response: `Je comprends votre question. Pourriez-vous être plus spécifique? Je peux vous aider avec des informations sur:

- Nos services (études et recherches, coopération internationale, gestion de projets, formations, achats de performances)
- Nos secteurs d'activités (agroécologie, gouvernance, ressources naturelles, entrepreneuriat, économie sociale, gestion des conflits)
- Notre équipe
- Comment nous contacter
- Notre vision et mission

Posez-moi une question plus précise ou utilisez les questions fréquentes ci-dessous!`
  }
}

